SELECT
    COALESCE(chart_no, '')                                       AS "chartNo",
    COALESCE(name, '')                                           AS "name",
    COALESCE(name_eng, '')                                       AS "nameEng",
    surgery_category                                             AS "surgeryCategory",
    TO_CHAR(surgery_date, 'YYYY-MM-DD')                          AS "surgeryDate",
    COALESCE(TO_CHAR(exam_date, 'YYYY-MM-DD'), '')               AS "examDate",
    COALESCE(patient_type, '')                                   AS "patientType",
    COALESCE(TO_CHAR(surgery_reserve_date, 'YYYY-MM-DD'), '')    AS "surgeryReserveDate",
    COALESCE(TO_CHAR(surgery_reg_date, 'YYYY-MM-DD'), '')        AS "surgeryRegDate",
    COALESCE(surgery_time, '')                                   AS "surgeryTime",
    COALESCE(surgery_r, '')                                      AS "surgeryR",
    COALESCE(surgery_l, '')                                      AS "surgeryL",
    COALESCE(recommended_r, '')                                  AS "recommendedR",
    COALESCE(recommended_l, '')                                  AS "recommendedL",
    COALESCE(estimate, '')                                       AS "estimate",
    COALESCE(surgery_rate, '')                                   AS "surgeryRate",
    COALESCE(payment, '')                                        AS "payment",
    COALESCE(surgeon, '')                                        AS "surgeon",
    COALESCE(counselor, '')                                      AS "counselor",
    COALESCE(doctor, '')                                         AS "doctor",
    COALESCE(optometrist, '')                                    AS "optometrist",
    COALESCE(birth, '')                                          AS "birth",
    COALESCE(lunar, '')                                          AS "lunar",
    COALESCE(phone1, '')                                         AS "phone1",
    COALESCE(phone2, '')                                         AS "phone2",
    COALESCE(email, '')                                          AS "email",
    COALESCE(zip, '')                                            AS "zip",
    COALESCE(addr1, '')                                          AS "addr1",
    COALESCE(addr2, '')                                          AS "addr2",
    COALESCE(memo, '')                                           AS "memo",
    COALESCE(grade, '')                                          AS "grade",
    COALESCE(job, '')                                            AS "job",
    COALESCE(TO_CHAR(last_visit, 'YYYY-MM-DD'), '')              AS "lastVisit",
    COALESCE(route, '')                                          AS "route",
    COALESCE(section, '')                                        AS "section",
    COALESCE(motive_l, '')                                       AS "motiveL",
    COALESCE(motive_m, '')                                       AS "motiveM",
    COALESCE(motive_s, '')                                       AS "motiveS",
    COALESCE(motive_memo, '')                                    AS "motiveMemo",
    COALESCE(exam_memo, '')                                      AS "examMemo",
    COALESCE(insurance, '')                                      AS "insurance",
    COALESCE(nationality, '')                                    AS "nationality"
  FROM list_surgery
 WHERE surgery_date >= CAST(:from AS DATE)
   AND surgery_date <= CAST(:to   AS DATE)
 ORDER BY surgery_date, name, surgery_category
