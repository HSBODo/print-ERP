SELECT
    TO_CHAR(reserve_date, 'YYYY-MM-DD')       AS "reserveDate",
    COALESCE(reserve_num, '')                  AS "reserveNum",
    COALESCE(reserve_time, '')                 AS "reserveTime",
    COALESCE(end_time, '')                     AS "endTime",
    COALESCE(state, '')                        AS "state",
    COALESCE(state_code, '')                   AS "stateCode",
    COALESCE(reserve_type, '')                 AS "reserveType",
    COALESCE(reserve_jinryo_code, '')          AS "reserveJinryoCode",
    COALESCE(patient_type, '')                 AS "patientType",
    COALESCE(old_flag, '')                     AS "oldFlag",
    COALESCE(today_flag, '')                   AS "todayFlag",
    COALESCE(happy_call, '')                   AS "happyCall",
    COALESCE(chart_no, '')                     AS "chartNo",
    COALESCE(name, '')                         AS "name",
    COALESCE(name_eng, '')                     AS "nameEng",
    COALESCE(grade, '')                        AS "grade",
    COALESCE(birth, '')                        AS "birth",
    COALESCE(lunar, '')                        AS "lunar",
    COALESCE(phone1, '')                       AS "phone1",
    COALESCE(phone2, '')                       AS "phone2",
    COALESCE(email, '')                        AS "email",
    COALESCE(zip, '')                          AS "zip",
    COALESCE(addr1, '')                        AS "addr1",
    COALESCE(addr2, '')                        AS "addr2",
    COALESCE(doctor, '')                       AS "doctor",
    COALESCE(counselor, '')                    AS "counselor",
    COALESCE(registered_by, '')                AS "registeredBy",
    COALESCE(comment, '')                      AS "comment",
    COALESCE(route, '')                        AS "route",
    COALESCE(section, '')                      AS "section",
    COALESCE(motive_l, '')                     AS "motiveL",
    COALESCE(motive_m, '')                     AS "motiveM",
    COALESCE(motive_s, '')                     AS "motiveS",
    COALESCE(motive_memo, '')                  AS "motiveMemo",
    COALESCE(job, '')                          AS "job",
    COALESCE(last_visit, '')                   AS "lastVisit",
    COALESCE(insurance, '')                    AS "insurance",
    COALESCE(nationality, '')                  AS "nationality",
    COALESCE(memo, '')                         AS "memo"
  FROM list_outpatient
 WHERE reserve_date >= CAST(:from AS DATE)
   AND reserve_date <= CAST(:to   AS DATE)
 ORDER BY reserve_date, id
