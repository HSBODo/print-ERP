-- =========================================================
-- 문자 수신거부 목록 (V60)
-- Profile: postgres-mart
--
-- 왜 필요한가.
--   홀딩은 (차트번호 + 수술일) **행 하나**에만 걸린다. 그런데 자동 적재는 새 수술이 생기면
--   새 행을 SENDABLE 로 만든다 — 즉 "그만 보내주세요"라고 한 환자도 **다음 수술 때 되살아난다.**
--   사람 단위로 한 번 등록하면 계속 막히는 목록이 따로 있어야 그 구멍이 막힌다.
--
--   등록 경로가 여럿이어도(데스크·전화·나중에 080) 결국 이 표 하나로 모이게 해서,
--   차단 로직은 여기만 보게 한다. 080 을 붙일 때 동기화 잡이 source 만 다르게 넣으면 된다.
--
-- ⚠️ 이 표는 보유기간 만료로 지우면 안 된다 — 지우면 다시 발송된다.
--    대상·이력의 자동 파기 대상에서 **제외**한다(기획서 12장).
-- =========================================================

CREATE TABLE IF NOT EXISTS sms_opt_out (
    id         BIGSERIAL     PRIMARY KEY,
    -- 매칭 키. 하이픈 없는 01012345678 형태로 정규화해 저장한다(대상 phone 과 같은 규칙).
    phone      VARCHAR(20)   NOT NULL,
    -- 참고용. 번호가 바뀌어도 누구였는지 알 수 있게 남긴다(매칭은 번호로 한다).
    chart_no   VARCHAR(50),
    name       VARCHAR(100),
    -- MANUAL(화면에서 등록) / SOLAPI_080(수신거부 서비스 동기화) …
    source     VARCHAR(20)   NOT NULL,
    created_at TIMESTAMP,
    created_by VARCHAR(50)
);

-- 같은 번호를 두 번 등록하지 않는다. 등록은 멱등이어야 한다 —
-- 여러 경로(데스크·080)로 같은 사람이 들어와도 한 줄만 남는다.
CREATE UNIQUE INDEX IF NOT EXISTS ux_sms_opt_out_phone ON sms_opt_out (phone);
