SELECT
    yr                  AS "year",
    wk                  AS "week",
    TO_CHAR(start_date, 'YYYY-MM-DD') AS "startDate",
    TO_CHAR(end_date,   'YYYY-MM-DD') AS "endDate",
    reservations,
    call_cnt            AS "call",
    online,
    intro_general       AS "introGeneral",
    intro_customer      AS "introCustomer",
    intro_staff         AS "introStaff",
    job_office          AS "jobOffice",
    job_student         AS "jobStudent",
    job_etc             AS "jobEtc",
    exam_total          AS "examTotal",
    vision_exam         AS "visionExam",
    cataract_exam       AS "cataractExam",
    one_day             AS "oneDay",
    vision_booked       AS "visionBooked",
    cataract_exam_eyes  AS "cataractExamEyes",
    cataract_booked     AS "cataractBooked",
    one_day_booked      AS "oneDayBooked",
    stop_count          AS "stopCount",
    exam_general_base   AS "examGeneralBase",
    booked_general      AS "bookedGeneral",
    vision_surgery      AS "visionSurgery",
    cataract_surgery    AS "cataractSurgery",
    total_surgery       AS "totalSurgery",
    outpatient
  FROM mart_weekly_report
 WHERE yr IN (:years)
 ORDER BY yr, wk
