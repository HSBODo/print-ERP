--   시드로 덮으면 실제 값의 정확도가 떨어지고 실측 검증(어느 컬럼이 실제로 비는지) 도 불가.
--   → 예약 3종만 시드로 두고 나머지 20개는 배치값 유지.
--
-- 원천 (월간 골든):
