/**
 * 그룹 코드에 맞는 차수 문구. 문구가 없으면 빈 문자열이고,
 * 화면은 그 자리에 "문구 미확정"을 띄운다 — 다른 수술 문구로 대신 보여주지 않는다.
 *
 * delayed = 기준일이 재조정된 대상. 2·3차만 다른 문구를 쓰고 1차는 기본 문구 그대로다.
 */
export const templateTextOf = (groupCode: string, tierIndex: number, delayed = false): string => {
  if (delayed && tierIndex > 0) return DELAYED_TEXTS[groupCode]?.[tierIndex - 1] ?? ''
  return TEMPLATE_TEXTS[groupCode]?.[tierIndex] ?? ''
}

const KOREAN_DATE = (iso: string) => {
  if (!iso) return ''
  const [y, m, d] = iso.split('-').map(Number)
  return `${y}년 ${m}월 ${d}일`
}

/**
 * 치환자를 실제 값으로 바꾼다 — 미리보기는 **나갈 문장 그대로** 보여야 검수가 된다.
 * 발송 시에는 서버(문자)나 솔라피(알림톡)가 같은 자리를 채운다.
 */
export const fillTemplate = (text: string, target: SmsTarget): string =>
  text
    .replaceAll('#{이름}', target.name || '고객')
    .replaceAll('#{수술일}', KOREAN_DATE(target.surgeryDate))
