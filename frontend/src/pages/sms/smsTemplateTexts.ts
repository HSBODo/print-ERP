/**
 * 지연 발송용 2·3차 본문. 1차 지연 요청이 오면 빈 문자열을 반환한다 —
 * 미리보기는 그런 경우 API 승인 본문을 그대로 쓰도록 되어 있다.
 * {@code tier} 는 1-based (1/2/3).
 */
export const delayedTextOf = (groupCode: string, tier: number): string => {
  if (tier < 2) return ''
  return DELAYED_TEXTS[groupCode]?.[tier - 2] ?? ''
}

const KOREAN_DATE = (iso: string) => {
  if (!iso) return ''
  const [y, m, d] = iso.split('-').map(Number)
  return `${y}년 ${m}월 ${d}일`
}

/**
 * 치환자를 실제 값으로 바꾼다 — 미리보기는 **나갈 문장 그대로** 보여야 검수가 된다.
 * 발송 시에는 서버(문자)나 솔라피(알림톡)가 같은 자리를 채운다.
 */
export const fillTemplate = (text: string, target: SmsTarget): string =>
  text
    .replaceAll('#{name}', target.name || '고객')
    .replaceAll('#{surgeryDate}', KOREAN_DATE(target.surgeryDate))
